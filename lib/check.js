/**
 * Step ② — diagnosis and the auto-fixes that are safe to automate.
 *
 * Everything here is written to be reviewable before it lands: `planFixes`
 * returns the exact file writes, and `applyFixes` performs them with a backup of
 * every file it touches. Nothing in this module talks to the network.
 *
 * The rule of thumb for what may be auto-fixed: mechanical shape problems
 * (a missing manifest field, a patch file in the wrong shape, an official package
 * in the wrong dependency block) are safe. Anything that states a *fact about the
 * plugin* — its description, its category, its screenshots — is only ever a
 * draft, because the guide makes the author responsible for accuracy.
 *
 * @module lib/check.js
 */

import fs from 'node:fs'
import path from 'node:path'
import { inspectPackage } from './scan.js'
import { checkPackage, summarize, yamlScalar, CATEGORIES, analyzePeerRange, normalizeRepoSlug } from './rules.js'

/** Minimal, correct patch file for a package whose bundle declares no patch. */
export function minimalPatchYaml(packageName, pluginId) {
  const id = pluginId ?? packageName.replace(/^@[^/]+\//, '').replace(/^dsh-/, '')
  return [
    '# Generated by dsh-onshelf — a top-level YAML array of loader patch entries.',
    '- insert:',
    '    - id: ' + yamlScalar(id),
    '      name: ' + yamlScalar(packageName),
    '      config: {}',
    '',
  ].join('\n')
}

/** The `dsh` block a package needs in order to be installable at all. */
function ensureBundleField(pkg, patchRel) {
  const next = structuredClone(pkg)
  next.dsh = next.dsh && typeof next.dsh === 'object' ? next.dsh : {}
  const bundle = next.dsh.bundle
  if (!bundle || typeof bundle !== 'object' || typeof bundle.patch !== 'string') {
    next.dsh.bundle = { ...(typeof bundle === 'object' ? bundle : {}), patch: patchRel }
  }
  return next
}

/** Move `@deepseek-ai/*` from dependencies to peerDependencies. */
function moveOfficialToPeer(pkg) {
  const next = structuredClone(pkg)
  const moved = {}
  for (const [name, range] of Object.entries(next.dependencies ?? {})) {
    if (name.startsWith('@deepseek-ai/')) {
      moved[name] = range
      delete next.dependencies[name]
    }
  }
  if (Object.keys(moved).length === 0) return next
  // Emptying the block must remove the key entirely: `"dependencies": {}` is still
  // a declaration, and `null` would not even be valid package.json.
  if (!next.dependencies || Object.keys(next.dependencies).length === 0) delete next.dependencies
  next.peerDependencies = { ...(next.peerDependencies ?? {}) }
  for (const [name, range] of Object.entries(moved)) {
    // Keep an existing, more specific range rather than overwriting it.
    if (!next.peerDependencies[name]) next.peerDependencies[name] = range
  }
  return next
}

/**
 * Build the file-write plan for the fixable findings.
 *
 * Returns `{ writes: [{ file, before, after, kind }], skipped: [...] }` where
 * `before` is the current text (null when the file does not exist). Callers can
 * show this verbatim — it is the diff the user approves.
 */
export function planFixes(pkg, findings, options = {}) {
  const dir = pkg.dir
  const pkgFile = path.join(dir, 'package.json')
  const writes = []
  const skipped = []

  const wanted = new Set(findings.filter(f => f.fixable && f.fix).map(f => f.fix))
  if (wanted.size === 0) return { writes, skipped }

  let pkgObj = structuredClone(pkg.packageJson)
  let pkgChanged = false

  const patchRel = (() => {
    const declared = pkgObj.dsh?.bundle && typeof pkgObj.dsh.bundle === 'object' ? pkgObj.dsh.bundle.patch : null
    if (typeof declared === 'string' && declared.trim() !== '') return declared
    if (typeof pkgObj.dsh?.bundle === 'string' && pkgObj.dsh.bundle.trim() !== '') return pkgObj.dsh.bundle
    return './cordis.patch.yml'
  })()

  if (wanted.has('add-bundle')) {
    pkgObj = ensureBundleField(pkgObj, patchRel)
    pkgChanged = true
  }

  if (wanted.has('move-official-to-peer')) {
    pkgObj = moveOfficialToPeer(pkgObj)
    pkgChanged = true
  }

  if (wanted.has('fix-peer-range')) {
    const finding = findings.find(f => f.fix === 'fix-peer-range')
    const suggested = finding?.suggested ?? '>=0.0.1-rc.1 <0.1.0 || >=0.1.0-rc.1 <0.2.0-0'
    pkgObj.peerDependencies = { ...(pkgObj.peerDependencies ?? {}) }
    let touched = false
    for (const name of Object.keys(pkgObj.peerDependencies)) {
      if (!name.startsWith('@deepseek-ai/')) continue
      if (analyzePeerRange(pkgObj.peerDependencies[name]).ok !== false) continue
      pkgObj.peerDependencies[name] = suggested
      touched = true
    }
    if (touched) pkgChanged = true
  }

  if (wanted.has('add-repository') && options.targetRepo) {
    // The draft holds whatever the author typed — `owner/repo`, or a full URL with
    // or without `/tree/main/...`. Normalise before writing, or the field ends up
    // as `git+https://github.com/https://github.com/...`.
    const slug = normalizeRepoSlug(options.targetRepo)
    if (slug && !pkgObj.repository) {
      pkgObj.repository = { type: 'git', url: `git+https://github.com/${slug}.git` }
      pkgChanged = true
    }
  }

  if (pkgChanged) {
    const before = safeRead(pkgFile)
    writes.push({
      file: pkgFile,
      kind: 'package.json',
      before,
      after: JSON.stringify(pkgObj, null, 2) + '\n',
    })
  }

  /* ---- cordis.patch.yml ---- */
  if (wanted.has('add-bundle') || wanted.has('create-patch')) {
    const patchFile = path.resolve(dir, patchRel)
    const before = safeRead(patchFile)
    const existing = before ?? ''
    // A top-level array is a *document* property, not a per-line one: the first
    // meaningful line must itself start the sequence. A regex with the `m` flag
    // would happily match a nested `- id:` line and call a mapping an array.
    const firstMeaningful = existing
      .split(/\r?\n/)
      .find(line => line.trim() !== '' && !line.trim().startsWith('#'))
    const isArray = firstMeaningful !== undefined && firstMeaningful.trimStart().startsWith('-')

    if (before === null || before.trim() === '' || !isArray) {
      writes.push({
        file: patchFile,
        kind: 'cordis.patch.yml',
        before,
        after: minimalPatchYaml(pkgObj.name, options.pluginId),
      })
    } else if (wanted.has('create-patch') && !/\binsert\b/.test(existing)) {
      writes.push({
        file: patchFile,
        kind: 'cordis.patch.yml',
        before,
        after: `${existing.replace(/\s*$/, '\n')}- insert:\n    - id: ${yamlScalar(pluginId(pkgObj.name))}\n      name: ${yamlScalar(pkgObj.name)}\n      config: {}\n`,
      })
    } else {
      skipped.push({ fix: 'create-patch', reason: 'patch 文件已经是合规的顶层数组' })
    }
  }

  return { writes, skipped }
}

function pluginId(packageName) {
  return String(packageName).replace(/^@[^/]+\//, '').replace(/^dsh-/, '')
}

function safeRead(file) {
  try {
    return fs.readFileSync(file, 'utf8')
  } catch {
    return null
  }
}

/**
 * Apply a plan. Every file that already exists is copied to
 * `<file>.onshelf-backup` first; files this run *creates* are recorded as such so
 * undo can remove them rather than leave an empty file behind.
 *
 * When `options.manifestFile` is given, the applied list is also written there, so
 * an undo still works after the page that triggered the fix is gone.
 */
export function applyFixes(plan, options = {}) {
  const applied = []
  const failures = []
  for (const write of plan.writes) {
    try {
      const existed = write.before !== null && write.before !== undefined
      if (existed) {
        const backup = `${write.file}.onshelf-backup`
        if (!fs.existsSync(backup)) fs.copyFileSync(write.file, backup)
      }
      fs.mkdirSync(path.dirname(write.file), { recursive: true })
      fs.writeFileSync(write.file, write.after, 'utf8')
      applied.push({ file: write.file, kind: write.kind, created: !existed })
    } catch (error) {
      failures.push({ file: write.file, reason: error?.message ?? String(error) })
    }
  }
  if (options.manifestFile) {
    try {
      fs.mkdirSync(path.dirname(options.manifestFile), { recursive: true })
      fs.writeFileSync(options.manifestFile, JSON.stringify({ at: new Date().toISOString(), applied }, null, 2), 'utf8')
    } catch { /* the manifest is a convenience, not a correctness requirement */ }
  }
  return { applied, failures, dryRun: options.dryRun === true }
}

/** Read a manifest written by `applyFixes`. Returns `[]` when there is none. */
export function readFixManifest(file) {
  try {
    const parsed = JSON.parse(fs.readFileSync(file, 'utf8'))
    return Array.isArray(parsed?.applied) ? parsed.applied : []
  } catch {
    return []
  }
}

/**
 * Undo a fix run.
 *
 * `files` entries may be `{ file, created }` objects (from `applyFixes`, which is
 * what makes "delete the file we created" possible) or plain paths.
 */
export function undoFixes(files) {
  const restored = []
  const removed = []
  const failures = []
  for (const entry of files) {
    const file = typeof entry === 'string' ? entry : entry.file
    const created = typeof entry === 'object' && entry !== null && entry.created === true
    if (!file) continue
    const backup = `${file}.onshelf-backup`
    try {
      if (created) {
        if (fs.existsSync(file)) fs.unlinkSync(file)
        removed.push(file)
        continue
      }
      if (!fs.existsSync(backup)) {
        failures.push({ file, reason: '没有备份文件' })
        continue
      }
      fs.copyFileSync(backup, file)
      fs.unlinkSync(backup)
      restored.push(file)
    } catch (error) {
      failures.push({ file, reason: error?.message ?? String(error) })
    }
  }
  return { restored, removed, failures }
}

/**
 * Full diagnosis for one package: re-read it from disk (so the result reflects
 * any fix already applied), run the rulebook, and attach a fix plan.
 */
export function diagnose(dir, entry = {}, context = {}) {
  const pkg = inspectPackage(dir)
  if (!pkg) return { ok: false, error: `不是插件目录（缺少可解析的 package.json）：${dir}` }
  const findings = checkPackage(pkg, entry, context)
  const plan = planFixes(pkg, findings, context)
  return {
    ok: true,
    dir,
    name: pkg.name,
    version: pkg.version,
    findings,
    summary: summarize(findings),
    fixPlan: plan,
  }
}

